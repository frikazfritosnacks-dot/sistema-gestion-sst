// Helper to get unique areas dynamically from dataset
export function obtenerAreasUnicas(items: RiesgoGTC45Item[]): string[] {
  const setAreas = new Set<string>();
  items.forEach((item) => {
    if (item.zonaLugar && item.zonaLugar.trim().length > 0) {
      setAreas.add(item.zonaLugar.trim());
    }
  });
  return Array.from(setAreas).sort((a, b) => a.localeCompare(b));
}

// Helper to filter hazards by area
export function obtenerRiesgosPorArea(items: RiesgoGTC45Item[], area: string): RiesgoGTC45Item[] {
  if (!area || area === 'TODAS' || area === 'Todas las áreas') return items;
  return items.filter((item) => item.zonaLugar.toLowerCase() === area.toLowerCase());
}

